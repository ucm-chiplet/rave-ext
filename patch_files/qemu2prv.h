void events_and_values_to_pcf(FILE * fd){
	event_info * curr = first_event_info;
	while(curr != NULL){
		fprintf(fd,"EVENT_TYPE\n9\t%ld\t%s\n",curr->ID, curr->name);
		value_info * values = curr->values;
		if (values!=NULL){
			fprintf(fd,"VALUES\n");
			while(values!=NULL){
				fprintf(fd,"%ld\t%s\n",values->ID, values->name);
				values = values->next;
			}
		}
		curr = curr->next;
	}
}	
